#!/usr/bin/env python3
"""Generates rom/demo.s: a demo cartridge written for this project (own code): per-line kernel with colour gradient, playfield, two
sprites, missiles and a ball. usage: gen_demo.py out.s"""
import sys
H = 192
def tab(name, f, page=True):
    rows = [f(y) & 255 for y in range(H)]
    s = '    .org $%04X\n%s:\n' % (tab.org, name)
    for i in range(0, H, 16): s += '    .byte ' + ', '.join('$%02X' % v for v in rows[i:i+16]) + '\n'
    tab.org += 0x100
    return s
tab.org = 0xF200
smiley = [0x3C,0x42,0xA5,0x81,0xA5,0x99,0x42,0x3C]
arrow  = [0x18,0x3C,0x7E,0xFF,0x18,0x18,0x18,0x18]
def spr(rows, ranges):
    def f(y):
        for a in ranges:
            if a <= y < a + 16: return rows[(y - a) // 2]
        return 0
    return f
tables = [
  ('bk',  lambda y: 0x80 + ((y // 24) << 1)),
  ('pf0', lambda y: 0xF0 if (y // 16) % 2 == 0 else 0xA0),
  ('pf1', lambda y: 0xAA if (y // 8) % 2 else 0x81),
  ('pf2', lambda y: 0x0F if (y // 32) % 2 else 0xF0),
  ('g0',  spr(smiley, (32, 100))),
  ('g1',  spr(arrow, (56, 140))),
  ('en',  lambda y: 0x02 if (80 <= y < 90 or 150 <= y < 170) else 0),
]
src = '''; demo cartridge (generated by tools/gen_demo.py)
VSYNC = $00
VBLANK = $01
WSYNC = $02
NUSIZ0 = $04
NUSIZ1 = $05
COLUP0 = $06
COLUP1 = $07
COLUPF = $08
COLUBK = $09
CTRLPF = $0A
REFP1 = $0C
PF0 = $0D
PF1 = $0E
PF2 = $0F
RESP0 = $10
RESP1 = $11
RESM0 = $12
RESM1 = $13
RESBL = $14
GRP0 = $1B
GRP1 = $1C
ENAM0 = $1D
ENAM1 = $1E
ENABL = $1F
HMP0 = $20
HMP1 = $21
HMM0 = $22
HMM1 = $23
HMBL = $24
HMOVE = $2A
HMCLR = $2B
CXCLR = $2C
CXP0FB = $02
FRAME = $80
    .org $F000
start:
    SEI
    CLD
    LDX #$FF
    TXS
    LDA #0
clr:
    STA $00,X
    DEX
    BNE clr
    LDA #$1E
    STA COLUP0
    LDA #$4A
    STA COLUP1
    LDA #$C6
    STA COLUPF
    LDA #$13
    STA NUSIZ0
    LDA #$05
    STA NUSIZ1
    LDA #$31
    STA CTRLPF
    LDA #$08
    STA REFP1
    LDA #2
    STA ENAM1
frame:
    LDA #2
    STA WSYNC
    STA VSYNC
    STA WSYNC
    STA WSYNC
    LDA #0
    STA WSYNC
    STA VSYNC
    STA CXCLR
    LDX #30
vb:
    STA WSYNC
    DEX
    BNE vb
    STA WSYNC
    LDX #4
d0:
    DEX
    BNE d0
    STA RESP0
    STA WSYNC
    LDX #12
d1:
    DEX
    BNE d1
    STA RESP1
    STA WSYNC
    LDX #7
d2:
    DEX
    BNE d2
    STA RESM0
    STA WSYNC
    LDX #9
d3:
    DEX
    BNE d3
    STA RESM1
    STA WSYNC
    LDX #15
d4:
    DEX
    BNE d4
    STA RESBL
    STA WSYNC
    LDA #$F0
    STA HMP0
    LDA #$30
    STA HMP1
    LDA #$80
    STA HMM0
    STA HMBL
    STA HMOVE
    LDA #0
    STA VBLANK
    LDY #0
    STA WSYNC
line:
    LDA bk,Y
    STA COLUBK
    LDA pf0,Y
    STA PF0
    LDA pf1,Y
    STA PF1
    LDA pf2,Y
    STA PF2
    LDA g0,Y
    STA GRP0
    LDA g1,Y
    STA GRP1
    LDA en,Y
    STA ENAM0
    STA ENABL
    INY
    CPY #192
    STA WSYNC
    BNE line
    LDA #2
    STA VBLANK
    LDA CXP0FB
    STA $90
    INC FRAME
    LDX #28
os:
    STA WSYNC
    DEX
    BNE os
    JMP frame
'''
for n, f in tables: src += tab(n, f)
src += '    .org $FFFC\n    .word start\n    .word start\n'
open(sys.argv[1], 'w').write(src)
